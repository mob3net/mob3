package browser

import (
	"flag"
	"fmt"
	"os"
	"strconv"
	"strings"
	"time"
)

// Run executes the MOB³ command line and returns a process exit code.
func Run(args []string) int {
	fs := flag.NewFlagSet("mob3", flag.ContinueOnError)
	fs.SetOutput(os.Stderr)
	dump := fs.Bool("dump", false, "render the page to stdout and exit")
	widthFlag := fs.Int("width", 0, "layout width in columns (default: terminal width or 100)")
	noColor := fs.Bool("no-color", false, "disable ANSI colors in dump mode")
	forceColor := fs.Bool("color", false, "force ANSI colors in dump mode")
	ua := fs.String("ua", "", "custom User-Agent (default MOB3/1.0 (+terminal; +https://mob3.net))")
	search := fs.String("search", DefaultSearchURL, "search URL template with %s; empty disables search fallback")
	showVersion := fs.Bool("version", false, "print the version and exit")
	graphics := fs.String("graphics", "none", "image mode: none, auto, kitty, iterm or blocks")
	fs.StringVar(graphics, "g", "none", "alias for -graphics")
	noJS := fs.Bool("no-js", false, "disable page JavaScript")
	reader := fs.Bool("reader", false, "start in reader mode")
	dark := fs.Bool("dark", false, "start in dark mode")
	ignoreBlocks := fs.Bool("ignore-blocks", false, "load anti-bot/CAPTCHA pages instead of the blocked page")
	bookmarks := fs.String("bookmarks", "", "import a Netscape bookmark HTML file")
	home := fs.String("home", "about:home", "home URL opened at startup and by the Home button")
	textScale := fs.String("text-scale", "auto", "kitty scaled text: auto or off")
	jsMemory := fs.Int("js-memory", int(defaultJSMemoryLimit>>20), "JavaScript heap limit in MB (0 disables)")
	cache := fs.Int("cache", int(defaultResourceCacheLimit>>20), "in-memory resource cache limit in MB (0 disables)")
	fs.Usage = func() {
		fmt.Fprintf(os.Stderr, "Usage: %s [flags] [url|file]\n\n", os.Args[0])
		fmt.Fprintf(os.Stderr, "MOB³ %s — A small terminal browser with its own HTML/CSS engine.\n", Version)
		fmt.Fprintf(os.Stderr, "License: AGPL-3.0-only\n")
		fmt.Fprintf(os.Stderr, "Copyright (c) 2026 Milos Stojanovic\n\n")
		fs.PrintDefaults()
		fmt.Fprintf(os.Stderr, "\nExamples:\n  %s https://example.com\n  %s -dump -width 120 page.html\n  %s -dump -no-color https://go.dev\n", os.Args[0], os.Args[0], os.Args[0])
	}
	if err := fs.Parse(args); err != nil {
		if err == flag.ErrHelp {
			return 0
		}
		return 2
	}
	if *showVersion {
		fmt.Println(Version)
		return 0
	}

	start := *home
	if strings.TrimSpace(start) == "" {
		start = "about:home"
	}
	if fs.NArg() > 0 {
		start = fs.Arg(0)
	}

	interactive := !*dump && isTTY(os.Stdin) && isTTY(os.Stdout)
	graphicsMode := ParseGraphicsMode(*graphics)
	loader := NewLoader()
	loader.setCacheLimitMB(*cache)
	loader.noScripts = *noJS
	loader.noImages = graphicsMode == GraphicsNone
	loader.searchURL = *search
	loader.ignoreBlocks = *ignoreBlocks
	if *bookmarks != "" {
		marks, err := loadBookmarksFile(*bookmarks)
		if err != nil {
			fmt.Fprintf(os.Stderr, "mob3: cannot read bookmarks: %v\n", err)
			return 1
		}
		loader.bookmarks = marks
		loader.bookmarksSet = true
	}
	if *ua != "" {
		loader.userAgent = *ua
	}
	var jsMemLimit int64
	if *jsMemory > 0 {
		jsMemLimit = int64(*jsMemory) << 20
	}

	if !interactive {
		return dumpPage(loader, start, *widthFlag, *noColor, *forceColor, *noJS, *reader, *dark, jsMemLimit)
	}

	stdin := os.Stdin
	state, err := makeRaw(stdin)
	if err != nil {
		fmt.Fprintf(os.Stderr, "mob3: interactive mode unavailable (%v); rendering to stdout.\n", err)
		return dumpPage(loader, start, *widthFlag, *noColor, *forceColor, *noJS, *reader, *dark, jsMemLimit)
	}
	w, h, ok := terminalSize(os.Stdout)
	if !ok {
		w, h = 100, 30
	}
	if *widthFlag > 0 {
		w = *widthFlag
	}
	b := NewBrowser(w, h)
	b.setLoader(loader)
	b.reader = *reader
	b.dark = *dark
	b.home = *home
	if strings.TrimSpace(b.home) == "" {
		b.home = "about:home"
	}
	bookmarksValue := *bookmarks
	if bookmarksValue == "" {
		bookmarksValue = "(none)"
	}
	b.cliConfig = map[string]string{
		"-dump":      onOff(*dump),
		"-width":     strconv.Itoa(w),
		"-graphics":  *graphics,
		"-bookmarks": bookmarksValue,
		"-cache":     strconv.Itoa(*cache),
		"-color":     onOff(*forceColor),
		"-no-color":  onOff(*noColor),
		"-version":   Version,
	}
	b.color = !*noColor
	b.noJS = *noJS
	b.jsMemLimit = jsMemLimit
	switch strings.ToLower(strings.TrimSpace(*textScale)) {
	case "off", "none", "false":
		b.noBigText = true
	}
	cellW, cellH, _ := terminalCellPixels(os.Stdout)
	b.gfx = NewGFXRenderer(graphicsMode, cellW, cellH)

	kittyKeys := kittyKeyboardEnabled()
	var startSeq strings.Builder
	startSeq.WriteString("\x1b[?1049h\x1b[?25l\x1b[?7l\x1b[2J\x1b[?1000h\x1b[?1003h\x1b[?1006h")
	if kittyKeys {
		// Disambiguate escape codes, report event types, and report the text
		// generated by each key (shifted symbols and AltGr layouts).
		startSeq.WriteString("\x1b[>19u")
	}
	_, _ = os.Stdout.WriteString(startSeq.String())
	cleanup := func() {
		b.cancelLoadNow()
		var sb strings.Builder
		if kittyKeys {
			sb.WriteString("\x1b[<u")
		}
		sb.WriteString("\x1b[?1003l\x1b[?1000l\x1b[?1006l")
		b.gfx.Clear(&sb)
		sb.WriteString("\x1b[0m\x1b[?7h\x1b[?25h\x1b[?1049l")
		_, _ = os.Stdout.WriteString(sb.String())
		restoreTerm(stdin, state)
	}
	defer cleanup()

	keys := make(chan string, 32)
	b.keys = keys
	go readKeyEvents(stdin, keys)

	winch := make(chan os.Signal, 1)
	quitSig := make(chan os.Signal, 1)
	startSignalHandlers(winch, quitSig)
	defer stopSignalHandlers(winch, quitSig)

	// JS timers drive their own one-shot deadlines. An idle page with no
	// pending timers must not wake up and repaint on a fixed tick.
	var jsTimer *time.Timer
	defer func() {
		if jsTimer != nil {
			jsTimer.Stop()
		}
	}()
	var progressTimer *time.Timer
	defer func() {
		if progressTimer != nil {
			progressTimer.Stop()
		}
	}()
	usageTicker := time.NewTicker(2 * time.Second)
	defer usageTicker.Stop()

	b.sampleUsage()
	b.Navigate(start, true)
	for {
		if b.skipDraw {
			b.skipDraw = false
		} else {
			b.draw()
		}
		var timerC <-chan time.Time
		if d, ok := b.nextJSTimerDelay(); ok {
			if jsTimer == nil {
				jsTimer = time.NewTimer(d)
			} else {
				if !jsTimer.Stop() {
					select {
					case <-jsTimer.C:
					default:
					}
				}
				jsTimer.Reset(d)
			}
			timerC = jsTimer.C
		}
		var progressC <-chan time.Time
		if b.progressActive() {
			if progressTimer == nil {
				progressTimer = time.NewTimer(progressTickInterval)
			} else {
				if !progressTimer.Stop() {
					select {
					case <-progressTimer.C:
					default:
					}
				}
				progressTimer.Reset(progressTickInterval)
			}
			progressC = progressTimer.C
		}
		select {
		case k := <-keys:
			if k == "eof" {
				return 0
			}
			if b.HandleKey(k) {
				return 0
			}
		case <-winch:
			if nw, nh, ok := terminalSize(os.Stdout); ok {
				b.resize(nw, nh)
			}
		case res := <-b.loadCh:
			b.finishLoad(res)
		case <-timerC:
			// The loop body repaints once per event. Skip that repaint unless a
			// JS timer rebuilt the page: an idle page must not repaint at every
			// timer wakeup (this also re-sends graphics protocol image
			// placements and rewrites the chrome every frame).
			if !b.runJSTimers() {
				b.skipDraw = true
			}
		case <-progressC:
			if !b.tickProgress() {
				b.skipDraw = true
			}
		case <-usageTicker.C:
			// Refresh the memory readout only when the displayed value changed;
			// an unchanged readout does not justify a full repaint.
			before := b.usage.footer()
			b.sampleUsage()
			if b.consoleOpen || b.usage.footer() == before {
				b.skipDraw = true
			}
		case <-quitSig:
			return 0
		}
	}
}

func dumpPage(loader *Loader, target string, width int, noColor, forceColor, noJS, reader, dark bool, jsMemLimit int64) int {
	if width <= 0 {
		if w, _, ok := terminalSize(os.Stdout); ok {
			width = w
		} else {
			width = 100
		}
	}
	page, err := loader.Load(target, nil)
	if err != nil {
		fmt.Fprintf(os.Stderr, "mob3: %s\n", stripTerminalControls(err.Error()))
		return 1
	}
	if !noJS {
		runner := NewBrowser(width, 3)
		runner.noJS = false
		runner.jsMemLimit = jsMemLimit
		runner.startJS(page)
	}
	root, author := page.Root, page.Author
	if reader {
		if extracted, ok := extractReaderPage(page.Root, page.Title); ok {
			root, author = extracted, readerRules
		}
	}
	var layout *Layout
	if dark {
		layout = BuildLayoutDarkDeadline(root, author, width, false, time.Now().Add(maxFrameTime))
	} else {
		layout = BuildLayoutDeadline(root, author, width, false, time.Now().Add(maxFrameTime))
	}
	height := layout.Height
	if height < 1 {
		height = 1
	}
	if height > 20000 {
		height = 20000
	}
	pageFG := RGB(0x1f, 0x23, 0x28)
	if layout.Body != nil && layout.Body.Style != nil && layout.Body.Style.Color.Set {
		pageFG = layout.Body.Style.Color
	}
	pageBG := layout.PageBG
	if !pageBG.Set {
		pageBG = RGB(255, 255, 255)
	}
	g := NewGrid(width, height, pageFG, pageBG)
	PaintLayout(g, layout, 0, 0, height, nil, pageFG)
	color := !noColor && (forceColor || isTTY(os.Stdout))
	lines := g.Lines(color)
	for _, line := range lines {
		fmt.Println(line)
	}
	return 0
}

// Version is the MOB³ release version reported by -version. It is set at
// build time with -ldflags "-X browser/internal/browser.Version=v1.2.3" and
// remains "dev" for local builds that do not pass a version.
var Version = "dev"
