//go:build linux || darwin

package browser

import (
	"bufio"
	"os"
	"strconv"
	"strings"
	"unicode/utf8"
)

// readKeyEvents decodes keystrokes into symbolic names and streams them on ch.
func readKeyEvents(f *os.File, ch chan<- string) {
	r := bufio.NewReaderSize(f, 256)
	for {
		k, err := readKey(r)
		if err != nil {
			ch <- "eof"
			return
		}
		if k == "" {
			continue
		}
		ch <- k
	}
}

func readKey(r *bufio.Reader) (string, error) {
	b, err := r.ReadByte()
	if err != nil {
		return "", err
	}
	switch b {
	case 3:
		return "ctrl-c", nil
	case 9:
		return "tab", nil
	case 13, 10:
		return "enter", nil
	case 127, 8:
		return "backspace", nil
	case 27:
		return readEscape(r), nil
	case 0:
		return "ctrl-space", nil
	}
	if b < 32 {
		return "ctrl-" + string(rune('a'+b-1)), nil
	}
	if b < utf8.RuneSelf {
		return string(rune(b)), nil
	}
	// UTF-8 multibyte.
	buf := []byte{b}
	want := utf8Len(b)
	for len(buf) < want {
		nb, err := r.ReadByte()
		if err != nil {
			return "", err
		}
		buf = append(buf, nb)
	}
	if !utf8.Valid(buf) {
		return "", nil
	}
	return string(buf), nil
}

func utf8Len(b byte) int {
	switch {
	case b&0xf8 == 0xf0:
		return 4
	case b&0xf0 == 0xe0:
		return 3
	case b&0xe0 == 0xc0:
		return 2
	}
	return 1
}

// readAltKey decodes ESC followed by a key as an alt-<key> token. Terminals
// send Alt as an ESC prefix; when ESC arrives alone Buffered is empty and the
// caller reports a plain escape instead.
func readAltKey(r *bufio.Reader, b byte) string {
	switch b {
	case 127, 8:
		return "alt-backspace"
	case 13, 10:
		return "alt-enter"
	case 9:
		return "alt-tab"
	}
	if b < 32 {
		// Alt+control has no binding; leave it for the normal key decoder.
		_ = r.UnreadByte()
		return "esc"
	}
	buf := []byte{b}
	want := utf8Len(b)
	for len(buf) < want {
		nb, err := r.ReadByte()
		if err != nil {
			break
		}
		buf = append(buf, nb)
	}
	if !utf8.Valid(buf) {
		return "esc"
	}
	return "alt-" + string(buf)
}

// splitLegacyEvent removes a kitty event-type suffix (":1" press, ":2" repeat,
// ":3" release) from the last parameter of a legacy-encoded key and reports
// whether the key was released.
func splitLegacyEvent(params string) (string, bool) {
	i := strings.LastIndexByte(params, ':')
	if i < 0 || i+1 >= len(params) {
		return params, false
	}
	event, err := strconv.Atoi(params[i+1:])
	if err != nil {
		return params, false
	}
	return params[:i], event == 3
}

// modifierPrefix maps xterm/kitty modifier parameters (1 + shift|alt|ctrl|meta
// bit flags) to the key-name prefixes the rest of the browser understands.
func modifierPrefix(params string) string {
	parts := strings.Split(params, ";")
	if len(parts) < 2 {
		return ""
	}
	switch parts[len(parts)-1] {
	case "2":
		return "shift-"
	case "3":
		return "alt-"
	case "4":
		return "alt-shift-"
	case "5":
		return "ctrl-"
	case "6":
		return "ctrl-shift-"
	case "7":
		return "ctrl-alt-"
	case "8":
		return "ctrl-alt-shift-"
	}
	return ""
}

// kittyModifiers parses the modifier/event field of a kitty CSI u key. The
// modifier is 1 + shift|alt|ctrl|meta bits; the optional event is 1 press,
// 2 repeat or 3 release.
func kittyModifiers(field string) (mods, event int) {
	mods, event = 1, 1
	parts := strings.SplitN(field, ":", 3)
	if len(parts) > 0 {
		if n, err := strconv.Atoi(parts[0]); err == nil && n > 0 {
			mods = n
		}
	}
	if len(parts) > 1 {
		if n, err := strconv.Atoi(parts[1]); err == nil && n > 0 {
			event = n
		}
	}
	return mods, event
}

// decodeKittyKey turns a kitty keyboard protocol CSI u body into the same
// symbolic tokens the legacy decoder produces. Releases are ignored. The
// optional third field is the text generated by the key, which makes shifted
// symbols and AltGr layouts work.
func decodeKittyKey(body string) string {
	if body == "" || strings.HasPrefix(body, "?") || strings.HasPrefix(body, ">") {
		return ""
	}
	fields := strings.Split(body, ";")
	keyField := fields[0]
	if i := strings.IndexByte(keyField, ':'); i >= 0 {
		keyField = keyField[:i]
	}
	n, err := strconv.ParseUint(keyField, 10, 32)
	if err != nil {
		return ""
	}
	cp := rune(n)
	mods, event := 1, 1
	if len(fields) > 1 {
		mods, event = kittyModifiers(fields[1])
	}
	if event == 3 {
		return ""
	}
	bits := mods - 1

	text := ""
	if len(fields) > 2 {
		var b strings.Builder
		for _, p := range strings.Split(fields[2], ":") {
			if u, err := strconv.ParseUint(p, 10, 32); err == nil && u >= 32 {
				b.WriteRune(rune(u))
			}
		}
		text = b.String()
	}

	switch cp {
	case 27:
		return "esc"
	case 13, 57414:
		return "enter"
	case 9:
		if bits&1 != 0 {
			return "backtab"
		}
		return "tab"
	case 127, 8:
		switch {
		case bits&4 != 0:
			return "ctrl-backspace"
		case bits&2 != 0:
			return "alt-backspace"
		}
		return "backspace"
	case 32:
		if bits&4 != 0 {
			return "ctrl-space"
		}
	}
	if cp >= 57344 {
		// Functional keys, modifiers and keypad keys have no binding.
		return ""
	}
	// Alt keeps its prefix so the URL prompt's alt-b/f/d bindings work. AltGr
	// (ctrl+alt) instead produces text and is handled below.
	if bits&2 != 0 && bits&4 == 0 {
		if cp >= 32 {
			return "alt-" + string(cp)
		}
		return ""
	}
	if bits&2 != 0 && bits&4 != 0 && text != "" {
		return text
	}
	if bits&4 != 0 {
		if cp >= 'a' && cp <= 'z' {
			return "ctrl-" + string(cp)
		}
		if cp >= 'A' && cp <= 'Z' {
			return "ctrl-" + strings.ToLower(string(cp))
		}
		return ""
	}
	if bits&8 != 0 {
		return ""
	}
	if text != "" {
		return text
	}
	if cp < 32 {
		return ""
	}
	if bits&1 != 0 && cp >= 'a' && cp <= 'z' {
		return string(cp - 32)
	}
	return string(cp)
}

func readEscape(r *bufio.Reader) string {
	if r.Buffered() == 0 {
		return "esc"
	}
	b2, err := r.ReadByte()
	if err != nil {
		return "esc"
	}
	if b2 == '_' || b2 == '^' || b2 == 'P' || b2 == ']' {
		// Terminal reply (APC/DCS/OSC), for example a kitty graphics
		// acknowledgement. Drain it so it never reaches the key handler.
		drainTerminalReply(r)
		return ""
	}
	if b2 != '[' && b2 != 'O' {
		return readAltKey(r, b2)
	}
	var seq []byte
	for len(seq) < 32 {
		c, err := r.ReadByte()
		if err != nil {
			break
		}
		seq = append(seq, c)
		if c >= 0x40 && c <= 0x7e {
			break
		}
	}
	if len(seq) == 0 {
		return "esc"
	}
	final := seq[len(seq)-1]
	params := string(seq[:len(seq)-1])
	// Kitty reports event types on legacy-encoded keys too (arrows, Home,
	// Delete, …): CSI 1;mods:event A, where event 1 is press, 2 repeat and
	// 3 release. Drop the suffix before reading modifiers and ignore releases,
	// otherwise every arrow release moves a second time. CSI u keeps its own
	// field because decodeKittyKey parses the event itself.
	if final != 'u' && final != 'M' && final != 'm' {
		var release bool
		params, release = splitLegacyEvent(params)
		if release {
			return ""
		}
	}
	mod := modifierPrefix(params)
	switch final {
	case 'A':
		return mod + "up"
	case 'B':
		return mod + "down"
	case 'C':
		return mod + "right"
	case 'D':
		return mod + "left"
	case 'H':
		return mod + "home"
	case 'F':
		return mod + "end"
	case 'Z':
		return "backtab"
	case '~':
		base := params
		if i := strings.IndexByte(base, ';'); i >= 0 {
			base = base[:i]
		}
		switch base {
		case "1":
			return mod + "home"
		case "2":
			return mod + "insert"
		case "3":
			return mod + "delete"
		case "4":
			return mod + "end"
		case "5":
			return mod + "pgup"
		case "6":
			return mod + "pgdn"
		case "7":
			return mod + "home"
		case "8":
			return mod + "end"
		}
	case 'u':
		return decodeKittyKey(params)
	case 'M', 'm':
		if strings.HasPrefix(params, "<") {
			if ev, ok := parseSGRMouse(params, final == 'm'); ok {
				return mouseToken(ev)
			}
			return ""
		}
		if final == 'M' && params == "" {
			// Legacy X10 encoding: three raw bytes follow the final M.
			var buf [3]byte
			for i := range buf {
				c, err := r.ReadByte()
				if err != nil {
					return ""
				}
				buf[i] = c
			}
			if ev, ok := parseX10Mouse(buf[0], buf[1], buf[2]); ok {
				return mouseToken(ev)
			}
		}
	}
	return ""
}

// drainTerminalReply consumes an already-started APC/DCS/OSC sequence up to
// BEL or ST (ESC \).
func drainTerminalReply(r *bufio.Reader) {
	for {
		c, err := r.ReadByte()
		if err != nil {
			return
		}
		if c == 7 {
			return
		}
		if c == 27 {
			if next, err := r.Peek(1); err == nil && next[0] == '\\' {
				_, _ = r.ReadByte()
				return
			}
		}
	}
}
